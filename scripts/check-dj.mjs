import assert from 'node:assert/strict';
import { rulesDJPlan, filterDJCandidates } from '../server/src/services/djEngine.js';
import { getMusicSession, musicCookie } from '../server/src/services/neteaseSession.js';
const plan=rulesDJPlan('不要周杰伦，只想安静放松，也不要 Live');
assert.ok(plan.excludeTerms.includes('周杰伦'));assert.ok(plan.excludeTerms.includes('live'));
assert.ok(!plan.queries.some(q=>q.includes('周杰伦')));
assert.equal(rulesDJPlan('提提精神').label, '能量补给');
assert.equal(rulesDJPlan('更有活力', {description:'放松一下'}).label, '能量补给');
assert.equal(rulesDJPlan('更安静一点', {description:'专注工作'}).label, '专注时刻');
assert.equal(rulesDJPlan('换一批', {description:'陪我入睡'}).label, '慢慢入眠');
const tracks=[{id:'1',title:'song live',artist:'A',album:''},{id:'2',title:'song',artist:'周杰伦',album:''},{id:'3',title:'song',artist:'B',album:''},{id:'3',title:'song',artist:'B',album:''},{id:'4',title:'other',artist:'B',album:''}];
assert.deepEqual(filterDJCandidates(tracks,plan,['4']).map(t=>t.id),['3']);
const response={cookie:(name,value,options)=>{assert.equal(options.httpOnly,true);assert.equal(options.sameSite,'strict');response.id=value;}};
const one=getMusicSession({headers:{}},response,true);one.cookie='account-one';
const twoResponse={cookie:(name,value)=>{twoResponse.id=value;}};
const two=getMusicSession({headers:{}},twoResponse,true);two.cookie='account-two';
assert.notEqual(one.id,two.id);
assert.equal(musicCookie({headers:{cookie:'aurora_session='+response.id}}),'account-one');
assert.equal(musicCookie({headers:{cookie:'aurora_session='+twoResponse.id}}),'account-two');
assert.equal(musicCookie({headers:{cookie:'aurora_session=unknown'}}),'');
console.log('通过：明确排除歌手与 Live、去重与已播排除、每个浏览器会话独立账号、登录 Cookie 仅存在后端。');
